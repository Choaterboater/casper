const read = (file: string) => readFile(new URL(`../${file}`, import.meta.url), "utf8");

test("release-prep, not feature PRs, collects log and merged titles into grouped user-facing notes and updates the roadmap", async () => {
  const text = (await read("docs/RELEASE.md")).split("## v")[0]!;
  for (const clause of ["Feature PRs do not edit this file", "roadmap's **Built, not released** box", "release-prep PR", "git log <last tag>..HEAD", "merged PR titles", "one line per user-facing", "Added / Changed / Fixed", "omit internal-only work", "deduplicate", "same release-prep PR", "tests/release-install.test.ts", "tests/release-targets.test.ts"]) expect(text).toContain(clause);
});

test("new decisions are standalone, preserve the migrated numbers, old anchors and guard rails", async () => {
  const index = await read("docs/adr/0002-deliberate-choices.md");
  for (const [number, slug, title] of [
    [13, "project-check-approval", "Changing the project's checks needs its own answer"],
    [14, "background-updates", "Casper installs its own updates quietly by default"],
    [15, "agent-and-tmux-ownership", "Agents do not launch agents or touch unrelated tmux servers"],
  ] as const) {
    expect(index).toContain(`### ${number}. ${title}`);
    expect(index).toContain(`(0002/${number}-${slug}.md)`);
    const text = await read(`docs/adr/0002/${number}-${slug}.md`);
    expect(text).toStartWith(`# ${number}. ${title}`);
    for (const heading of ["**What:**", "**Why:**", "**Guard rails:**", "**A finding:**"]) expect(text).toContain(heading);
  }
  for (const rule of ["one decision per file", "Keep existing numbers", "Do not edit this index", "Supersede a decision", "bun tools/adr-index.ts"]) expect(index).toContain(rule);
  expect((await decisions()).map(entry => entry.file)).toEqual(expect.arrayContaining([
    "13-project-check-approval.md", "14-background-updates.md", "15-agent-and-tmux-ownership.md",
  ]));
  expect(await read("docs/adr/0002/13-project-check-approval.md")).toContain("Session-only is a quiet kept-file note");
});

test("new ADR files are discovered numerically without editing a shared index; the reader includes all their text", async () => {
  const root = await mkdtemp(path.join(os.tmpdir(), "casper-adr-index-"));
  try {
    const dir = path.join(root, "docs/adr/0002");
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(root, "docs/adr/0002-deliberate-choices.md"), "historical anchors");
    await writeFile(path.join(dir, "100-later.md"), "# 100. Later\nGuard rail B");
    await writeFile(path.join(dir, "15-first.md"), "# 15. First\nGuard rail A");
    await writeFile(path.join(dir, "README.md"), "not a decision");
    expect((await decisions(root)).map(entry => entry.file)).toEqual(["15-first.md", "100-later.md"]);
    expect(await deliberateChoices(root)).toBe("historical anchors\n\n# 15. First\nGuard rail A\n\n# 100. Later\nGuard rail B");
  } finally { await removeTempDir(root); }
});

